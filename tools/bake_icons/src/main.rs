//! Rasterize the vendored Lucide subset into a coverage atlas.
//!
//! Source SVGs are `crates/rndr_paint/icons/lucide/*.svg` (lucide-static,
//! ISC). The baker writes `crates/rndr_paint/src/icon_atlas.bin` and
//! `crates/rndr_core/src/icon_data.rs`. Order is the sorted icon id, which is
//! also the Private Use Area index from U+E100. Re-run from the repository
//! root after changing the SVG set:
//!
//! ```text
//! cargo run -p bake_icons
//! ```

use std::fs;
use std::path::Path;

use tiny_skia::Pixmap;
use usvg::{Options, Tree};

const CELL: u32 = 16;
const PITCH: u32 = 17;
const COLS: u32 = 16;
const SUPERSAMPLE: u32 = 4;
const RENDER: u32 = CELL * SUPERSAMPLE;
const VIEW: f32 = 24.0;
const SCALAR_BASE: u32 = 0xE100;

const ALIASES: &[(&str, &str)] = &[
    ("alerttriangle", "alert-triangle"),
    ("building", "building-2"),
    ("building2", "building-2"),
    ("filecode", "file-code"),
    ("home", "house"),
    ("mappin", "map-pin"),
    ("messagecircle", "message-circle"),
    ("shoppingbag", "shopping-bag"),
    ("trainfront", "train-front"),
];

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let svg_dir = root.join("crates/rndr_paint/icons/lucide");
    let mut ids: Vec<String> = fs::read_dir(&svg_dir)
        .unwrap_or_else(|err| panic!("read {}: {err}", svg_dir.display()))
        .map(|entry| entry.expect("svg entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "svg"))
        .map(|path| {
            path.file_stem()
                .expect("stem")
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    ids.sort();
    assert!(
        ids.len() < 256,
        "icon set must fit in the reserved Private Use block"
    );

    let rows = (ids.len() as u32).div_ceil(COLS);
    let width = COLS * PITCH;
    let height = rows * PITCH;
    let mut atlas = vec![0u8; (width * height) as usize];
    let mut ink = 0u32;

    for (index, id) in ids.iter().enumerate() {
        let path = svg_dir.join(format!("{id}.svg"));
        let source =
            fs::read_to_string(&path).unwrap_or_else(|err| panic!("{}: {err}", path.display()));
        let cell = rasterize(&source, &path);
        let covered = cell.iter().filter(|px| **px > 16).count();
        assert!(covered > 8, "{id} rasterized to an empty glyph");
        ink += covered as u32;
        let col = (index as u32) % COLS;
        let row = (index as u32) / COLS;
        let origin_x = col * PITCH;
        let origin_y = row * PITCH;
        for y in 0..CELL {
            for x in 0..CELL {
                let dst = ((origin_y + y) * width + origin_x + x) as usize;
                atlas[dst] = cell[(y * CELL + x) as usize];
            }
        }
    }

    let atlas_path = root.join("crates/rndr_paint/src/icon_atlas.bin");
    fs::write(&atlas_path, &atlas).unwrap_or_else(|err| panic!("write atlas: {err}"));
    let rust_path = root.join("crates/rndr_core/src/icon_data.rs");
    fs::write(&rust_path, generate(&ids)).unwrap_or_else(|err| panic!("write icon data: {err}"));
    println!(
        "baked {} icons, {width}x{height} coverage ({} bytes), {ink} ink samples",
        ids.len(),
        atlas.len()
    );
}

fn rasterize(source: &str, path: &Path) -> Vec<u8> {
    let svg = source.replace("currentColor", "#000");
    let tree = Tree::from_data(svg.as_bytes(), &Options::default())
        .unwrap_or_else(|err| panic!("parse {}: {err}", path.display()));
    let mut pixmap =
        Pixmap::new(RENDER, RENDER).unwrap_or_else(|| panic!("pixmap for {}", path.display()));
    let scale = RENDER as f32 / VIEW;
    resvg::render(
        &tree,
        tiny_skia::Transform::from_scale(scale, scale),
        &mut pixmap.as_mut(),
    );
    let pixels = pixmap.data();
    let mut cell = vec![0u8; (CELL * CELL) as usize];
    for y in 0..CELL {
        for x in 0..CELL {
            let mut sum = 0u32;
            for sy in 0..SUPERSAMPLE {
                for sx in 0..SUPERSAMPLE {
                    let px = (y * SUPERSAMPLE + sy) * RENDER + x * SUPERSAMPLE + sx;
                    let offset = px as usize * 4;
                    sum += u32::from(pixels[offset + 3]);
                }
            }
            cell[(y * CELL + x) as usize] = (sum / (SUPERSAMPLE * SUPERSAMPLE)) as u8;
        }
    }
    cell
}

fn generate(ids: &[String]) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `cargo run -p bake_icons`. Do not edit.\n");
    out.push_str("// Icon order is sorted id and is the Private Use index from U+E100.\n\n");
    out.push_str("/// Built-in Lucide icon, addressed by a Private Use scalar.\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n");
    out.push_str("#[repr(u16)]\n");
    out.push_str("pub enum Icon {\n");
    for (index, id) in ids.iter().enumerate() {
        out.push_str(&format!("    /// `{id}`.\n"));
        out.push_str(&format!("    {} = {index},\n", variant(id)));
    }
    out.push_str("}\n\n");
    out.push_str("impl Icon {\n");
    out.push_str("    /// Number of built-in icons.\n");
    out.push_str(&format!("    pub const COUNT: usize = {};\n\n", ids.len()));
    out.push_str("    /// Atlas index and Private Use offset.\n");
    out.push_str("    pub const fn index(self) -> usize {\n");
    out.push_str("        self as u16 as usize\n");
    out.push_str("    }\n\n");
    out.push_str("    /// Scalar embedded in a label to draw this icon.\n");
    out.push_str("    pub const fn scalar(self) -> char {\n");
    out.push_str("        match self {\n");
    for (index, id) in ids.iter().enumerate() {
        let code = SCALAR_BASE + index as u32;
        out.push_str(&format!(
            "            Self::{} => '\\u{{{code:04X}}}',\n",
            variant(id)
        ));
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    /// Canonical kebab-case id.\n");
    out.push_str("    pub const fn name(self) -> &'static str {\n");
    out.push_str("        ICON_NAMES[self.index()]\n");
    out.push_str("    }\n\n");
    out.push_str("    /// Icon stored at `index`, if it is in range.\n");
    out.push_str("    pub const fn from_index(index: usize) -> Option<Self> {\n");
    out.push_str("        if index >= Self::COUNT {\n");
    out.push_str("            return None;\n");
    out.push_str("        }\n");
    out.push_str("        Some(match index {\n");
    for (index, id) in ids.iter().enumerate() {
        out.push_str(&format!("            {index} => Self::{},\n", variant(id)));
    }
    out.push_str("            _ => return None,\n");
    out.push_str("        })\n");
    out.push_str("    }\n\n");
    out.push_str("    /// Icon for a baked Private Use scalar.\n");
    out.push_str("    pub fn from_scalar(ch: char) -> Option<Self> {\n");
    out.push_str("        let code = ch as u32;\n");
    out.push_str("        if code < ICON_SCALAR_START {\n");
    out.push_str("            return None;\n");
    out.push_str("        }\n");
    out.push_str("        Self::from_index((code - ICON_SCALAR_START) as usize)\n");
    out.push_str("    }\n\n");
    out.push_str("    /// Canonical id or a known alias (`home` → house).\n");
    out.push_str("    pub fn from_name(raw: &str) -> Option<Self> {\n");
    out.push_str("        let normalized = raw.trim().to_ascii_lowercase().replace('_', \"-\");\n");
    out.push_str("        let name = alias(normalized.as_str());\n");
    out.push_str("        ICON_NAMES\n");
    out.push_str("            .binary_search(&name)\n");
    out.push_str("            .ok()\n");
    out.push_str("            .and_then(Self::from_index)\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
    out.push_str("/// First Private Use scalar reserved for [`Icon`].\n");
    out.push_str(&format!(
        "pub const ICON_SCALAR_START: u32 = {SCALAR_BASE:#X};\n\n"
    ));
    out.push_str("/// Sorted canonical ids. The index is [`Icon::index`].\n");
    out.push_str("pub static ICON_NAMES: &[&str] = &[\n");
    for id in ids {
        out.push_str(&format!("    \"{id}\",\n"));
    }
    out.push_str("];\n\n");
    out.push_str("fn alias(name: &str) -> &str {\n");
    out.push_str("    match name {\n");
    for (alias, canonical) in ALIASES {
        out.push_str(&format!("        \"{alias}\" => \"{canonical}\",\n"));
    }
    out.push_str("        other => other,\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

fn variant(id: &str) -> String {
    let mut out = String::new();
    let mut cap = true;
    for ch in id.chars() {
        if ch == '-' {
            cap = true;
            continue;
        }
        if cap {
            out.extend(ch.to_uppercase());
            cap = false;
        } else {
            out.push(ch);
        }
    }
    if out.as_bytes().first().is_some_and(u8::is_ascii_digit) {
        out.insert(0, 'N');
    }
    out
}
